// RenderGlyphFontA returns a 12x24 dot matrix (24 rows of 12 dots: [24][12]uint8)
// represented as a flat slice of 24 * 12 = 288 bytes (1 = dot, 0 = space).
func RenderGlyphFontA(code byte) []uint8 {
	glyph := make([]uint8, 12*24)
	if code < 0x20 || code > 0x7E {
		// Non-printable control or undefined: return empty or box
		return glyph
	}
	matrix := font8x16[code-0x20]

	// Scale 8x16 into 12x24:
	// Horizontal: 8 dots mapped to 12 dots (1.5x scale: dots 0,1,2,3,4,5,6,7 -> stretch)
	// Vertical: 16 dots mapped to 24 dots (1.5x scale: row * 1.5)
	for y := 0; y < 24; y++ {
		srcY := (y * 16) / 24
		rowBits := matrix[srcY]
		for x := 0; x < 12; x++ {
			srcX := (x * 8) / 12
			if (rowBits & (1 << (7 - srcX))) != 0 {
				glyph[y*12+x] = 1
			}
		}
	}
	return glyph
}

// RenderGlyphFontB returns a 9x17 dot matrix (17 rows of 9 dots: [17][9]uint8)
// represented as a flat slice of 17 * 9 = 153 bytes.
func RenderGlyphFontB(code byte) []uint8 {
	glyph := make([]uint8, 9*17)
	if code < 0x20 || code > 0x7E {
		return glyph
	}
	matrix := font8x16[code-0x20]

	for y := 0; y < 17; y++ {
		srcY := (y * 16) / 17
		if srcY >= 16 {
			srcY = 15
		}
		rowBits := matrix[srcY]
		for x := 0; x < 9; x++ {
			srcX := (x * 8) / 9
			if srcX >= 8 {
				srcX = 7
			}
			if (rowBits & (1 << (7 - srcX))) != 0 {
				glyph[y*9+x] = 1
			}
		}
	}
	return glyph
}

// RenderGlyphKanji returns a 24x24 dot matrix (24 rows of 24 dots = 576 bytes).
func RenderGlyphKanji(c1, c2 byte) []uint8 {
	glyph := make([]uint8, 24*24)
	// Generate a distinctive geometric 24x24 Chinese character representation
	for y := 2; y < 22; y++ {
		for x := 2; x < 22; x++ {
			// Outer border + crosshairs + code-derived pattern
			if x == 2 || x == 21 || y == 2 || y == 21 || x == 11 || y == 11 || (x+y)%3 == int(c1+c2)%3 {
				glyph[y*24+x] = 1
			}
		}
	}
	return glyph
}
