func unpackRows12x24(rows [24]uint16) []uint8 {
	glyph := make([]uint8, 12*24)
	for y := 0; y < 24; y++ {
		mask := rows[y]
		for x := 0; x < 12; x++ {
			if (mask & (1 << (11 - x))) != 0 {
				glyph[y*12+x] = 1
			}
		}
	}
	return glyph
}

func unpackRows9x17(rows [17]uint16) []uint8 {
	glyph := make([]uint8, 9*17)
	for y := 0; y < 17; y++ {
		mask := rows[y]
		for x := 0; x < 9; x++ {
			if (mask & (1 << (8 - x))) != 0 {
				glyph[y*9+x] = 1
			}
		}
	}
	return glyph
}

func applyAccent12x24(rows *[24]uint16, acc accentType, upper bool, base byte) {
	// If base is lowercase 'i', clear the original dot at rows 5..6 before drawing the accent
	if base == 'i' {
		rows[5] = 0
		rows[6] = 0
	}
	topY := 6
	if upper {
		topY = 1
	}
	switch acc {
	case accAcute:
		rows[topY] |= 0x030
		rows[topY+1] |= 0x060
		rows[topY+2] |= 0x0C0
	case accGrave:
		rows[topY] |= 0x0C0
		rows[topY+1] |= 0x060
		rows[topY+2] |= 0x030
	case accCircumflex:
		rows[topY] |= 0x060
		rows[topY+1] |= 0x090
		rows[topY+2] |= 0x108
	case accDiaeresis:
		rows[topY+1] |= 0x198
		rows[topY+2] |= 0x198
	case accTilde:
		rows[topY+1] |= 0x0D0
		rows[topY+2] |= 0x168
	case accRing:
		rows[topY] |= 0x060
		rows[topY+1] |= 0x090
		rows[topY+2] |= 0x060
	case accCaron:
		rows[topY] |= 0x108
		rows[topY+1] |= 0x090
		rows[topY+2] |= 0x060
	case accCedilla:
		rows[21] |= 0x040
		rows[22] |= 0x020
		rows[23] |= 0x0C0
	case accStroke:
		if upper {
			rows[12] |= 0x3FE
		} else {
			rows[14] |= 0x1FC
		}
	}
}

func applyAccent9x17(rows *[17]uint16, acc accentType, upper bool, base byte) {
	if base == 'i' {
		rows[3] = 0
		rows[4] = 0
	}
	topY := 3
	if upper {
		topY = 0
	}
	switch acc {
	case accAcute:
		rows[topY] |= 0x018
		rows[topY+1] |= 0x030
	case accGrave:
		rows[topY] |= 0x030
		rows[topY+1] |= 0x018
	case accCircumflex:
		rows[topY] |= 0x020
		rows[topY+1] |= 0x050
	case accDiaeresis:
		rows[topY+1] |= 0x050
	case accTilde:
		rows[topY] |= 0x030
		rows[topY+1] |= 0x060
	case accRing:
		rows[topY] |= 0x020
		rows[topY+1] |= 0x050
		if topY+2 < 17 {
			rows[topY+2] |= 0x020
		}
	case accCaron:
		rows[topY] |= 0x050
		rows[topY+1] |= 0x020
	case accCedilla:
		rows[15] |= 0x020
		rows[16] |= 0x060
	case accStroke:
		rows[9] |= 0x0FE
	}
}

func renderBoxOrBlock(r rune, w, h int) []uint8 {
	switch r {
	case '░':
		glyph := make([]uint8, w*h)
		for y := 0; y < h; y++ {
			for x := 0; x < w; x++ {
				if y%2 == 0 && (x+(y/2)*2)%4 == 0 {
					glyph[y*w+x] = 1
				}
			}
		}
		return glyph
	case '▒':
		glyph := make([]uint8, w*h)
		for y := 0; y < h; y++ {
			for x := 0; x < w; x++ {
				if (x+y)%2 == 0 {
					glyph[y*w+x] = 1
				}
			}
		}
		return glyph
	case '▓':
		glyph := make([]uint8, w*h)
		for y := 0; y < h; y++ {
			for x := 0; x < w; x++ {
				if !(y%2 == 0 && (x+(y/2)*2)%4 == 0) {
					glyph[y*w+x] = 1
				}
			}
		}
		return glyph
	case '█':
		glyph := make([]uint8, w*h)
		for i := range glyph {
			glyph[i] = 1
		}
		return glyph
	case '▄':
		glyph := make([]uint8, w*h)
		for y := h / 2; y < h; y++ {
			for x := 0; x < w; x++ {
				glyph[y*w+x] = 1
			}
		}
		return glyph
	case '▀':
		glyph := make([]uint8, w*h)
		for y := 0; y < h/2; y++ {
			for x := 0; x < w; x++ {
				glyph[y*w+x] = 1
			}
		}
		return glyph
	case '▌':
		glyph := make([]uint8, w*h)
		for y := 0; y < h; y++ {
			for x := 0; x < w/2; x++ {
				glyph[y*w+x] = 1
			}
		}
		return glyph
	case '▐':
		glyph := make([]uint8, w*h)
		for y := 0; y < h; y++ {
			for x := w / 2; x < w; x++ {
				glyph[y*w+x] = 1
			}
		}
		return glyph
	case '■':
		glyph := make([]uint8, w*h)
		x0, x1 := w/4, w-w/4
		y0, y1 := h/3, h-h/3
		for y := y0; y < y1; y++ {
			for x := x0; x < x1; x++ {
				glyph[y*w+x] = 1
			}
		}
		return glyph
	}

	spec, ok := boxDrawingMap[r]
	if !ok {
		return nil
	}
	glyph := make([]uint8, w*h)
	cx := w / 2
	cy := h / 2

	setDot := func(x, y int) {
		if x >= 0 && x < w && y >= 0 && y < h {
			glyph[y*w+x] = 1
		}
	}

	// Up arm
	if spec.up == 1 {
		for y := 0; y <= cy; y++ {
			setDot(cx, y)
		}
	} else if spec.up == 2 {
		for y := 0; y <= cy; y++ {
			setDot(cx-1, y)
			setDot(cx+1, y)
		}
	}

	// Down arm
	if spec.down == 1 {
		for y := cy; y < h; y++ {
			setDot(cx, y)
		}
	} else if spec.down == 2 {
		for y := cy; y < h; y++ {
			setDot(cx-1, y)
			setDot(cx+1, y)
		}
	}

	// Left arm
	if spec.left == 1 {
		for x := 0; x <= cx; x++ {
			setDot(x, cy)
		}
	} else if spec.left == 2 {
		for x := 0; x <= cx; x++ {
			setDot(x, cy-1)
			setDot(x, cy+1)
		}
	}

	// Right arm
	if spec.right == 1 {
		for x := cx; x < w; x++ {
			setDot(x, cy)
		}
	} else if spec.right == 2 {
		for x := cx; x < w; x++ {
			setDot(x, cy-1)
			setDot(x, cy+1)
		}
	}

	return glyph
}

// RenderRuneFontA returns a native 12x24 dot matrix (288 bytes: 1 = dot, 0 = space)
// for any ASCII, International, CP437, CP850, or WCP1252 rune.
func RenderRuneFontA(r rune) []uint8 {
	if r >= 0x20 && r <= 0x7E {
		return unpackRows12x24(fontA12x24[r-0x20])
	}
	if r == 0x00A0 { // NBSP
		return make([]uint8, 12*24)
	}
	if acc, ok := accentedRuneMap[r]; ok {
		rows := fontA12x24[acc.base-0x20]
		applyAccent12x24(&rows, acc.accent, acc.upper, acc.base)
		return unpackRows12x24(rows)
	}
	if blk := renderBoxOrBlock(r, 12, 24); blk != nil {
		return blk
	}
	if sym, ok := specialSymbols12x24[r]; ok {
		return unpackRows12x24(sym)
	}
	return make([]uint8, 12*24)
}

// RenderRuneFontB returns a native 9x17 dot matrix (153 bytes: 1 = dot, 0 = space)
// for any ASCII, International, CP437, CP850, or WCP1252 rune.
func RenderRuneFontB(r rune) []uint8 {
	if r >= 0x20 && r <= 0x7E {
		return unpackRows9x17(fontB9x17[r-0x20])
	}
	if r == 0x00A0 { // NBSP
		return make([]uint8, 9*17)
	}
	if acc, ok := accentedRuneMap[r]; ok {
		rows := fontB9x17[acc.base-0x20]
		applyAccent9x17(&rows, acc.accent, acc.upper, acc.base)
		return unpackRows9x17(rows)
	}
	if blk := renderBoxOrBlock(r, 9, 17); blk != nil {
		return blk
	}
	if sym24, ok := specialSymbols12x24[r]; ok {
		var rows17 [17]uint16
		for y := 0; y < 17; y++ {
			sy := (y * 24) / 17
			for x := 0; x < 9; x++ {
				sx := (x * 12) / 9
				if (sym24[sy] & (1 << (11 - sx))) != 0 {
					rows17[y] |= (1 << (8 - x))
				}
			}
		}
		return unpackRows9x17(rows17)
	}
	return make([]uint8, 9*17)
}

// RenderGlyphFontA returns a native 12x24 dot matrix (24 rows of 12 dots = 288 bytes)
// for a single byte (resolving 0x80..0xFF via default CP437).
func RenderGlyphFontA(code byte) []uint8 {
	if code < 0x80 {
		return RenderRuneFontA(rune(code))
	}
	return RenderRuneFontA(DecodeByteToRune(code, 0, 0))
}

// RenderGlyphFontB returns a native 9x17 dot matrix (17 rows of 9 dots = 153 bytes)
// for a single byte (resolving 0x80..0xFF via default CP437).
func RenderGlyphFontB(code byte) []uint8 {
	if code < 0x80 {
		return RenderRuneFontB(rune(code))
	}
	return RenderRuneFontB(DecodeByteToRune(code, 0, 0))
}

// RenderGlyphKanji returns a native 24x24 Songti Chinese character dot matrix (576 bytes)
// from the HZK24 CGROM table.
func RenderGlyphKanji(c1, c2 byte) []uint8 {
	glyph := make([]uint8, 24*24)
	if len(kanjiSongti24x24) == 0 {
		return glyph
	}
	idx := (int(c1)*31 + int(c2)) % len(kanjiSongti24x24)
	rows := kanjiSongti24x24[idx]
	for y := 0; y < 24; y++ {
		mask := rows[y]
		for x := 0; x < 24; x++ {
			if (mask & (1 << (23 - x))) != 0 {
				glyph[y*24+x] = 1
			}
		}
	}
	return glyph
}
